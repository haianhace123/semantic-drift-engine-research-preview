@dataclass(frozen=True)
class DependencyImpactCase:
    case_id: str
    category: str
    graph: DependencyGraph
    changed_node_ids: tuple[str, ...]
    expected_affected_node_ids: tuple[str, ...]
    expected_invalidation_candidate_ids: tuple[str, ...]
    expected_critical_node_ids: tuple[str, ...]


def _node(
    node_id: str,
    kind: str,
    *,
    materialized: bool = False,
    critical: bool = False,
) -> KnowledgeNode:
    return KnowledgeNode(
        id=node_id,
        kind=kind,  # type: ignore[arg-type]
        materialized=materialized,
        critical=critical,
    )


